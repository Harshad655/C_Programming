void Add()
{
    int N1 = 0, N2 = 0, Sum = 0;

    printf("Enter Number 1 : ");
    scanf("%d",&N1);
    printf("Enter Number 2 : ");
    scanf("%d",&N2);

    Sum = N1+N2;

    printf("Addition Of %d And %d",N1,N2,Sum);
    return;
}
